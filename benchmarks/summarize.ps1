# Summarizes a measure.ps1 runs.jsonl: median and range of each metric per
# tool and VU level, over measured runs only (warm-ups are excluded).
# Writes summary.csv and summary.md next to runs.jsonl.
#
#   ./benchmarks/summarize.ps1 -Runs benchmarks/results/2026-10-01-phase0/raw/runs.jsonl
param([Parameter(Mandatory)] [string] $Runs)

$ErrorActionPreference = 'Stop'
$inv = [Globalization.CultureInfo]::InvariantCulture
$dash = [char]0x2013  # en dash; kept as a code so this file stays ASCII
$dir = Split-Path (Resolve-Path $Runs).Path -Parent
$rows = Get-Content -Encoding UTF8 $Runs | Where-Object { $_.Trim() } | ForEach-Object { $_ | ConvertFrom-Json } |
  Where-Object { $_.kind -eq 'run' }

$metrics = [ordered]@{
  cpuPercent       = 'CPU %'
  peakPrivateMB    = 'Peak memory MB'
  avgPrivateMB     = 'Avg memory MB'
  requestsPerSec   = 'Requests/sec'
  p50Ms            = 'p50 ms'
  p95Ms            = 'p95 ms'
  p99Ms            = 'p99 ms'
  errors           = 'Errors'
  errorRatePct     = 'Error rate %'
  serverCpuPercent = 'Server CPU %'
}

function Get-Stats([object[]] $values) {
  $v = @($values | Where-Object { $null -ne $_ } | ForEach-Object { [double]$_ } | Sort-Object)
  if ($v.Count -eq 0) { return $null }
  $n = $v.Count
  if ($n % 2) { $median = $v[($n - 1) / 2] } else { $median = ($v[$n / 2 - 1] + $v[$n / 2]) / 2 }
  return @{ Median = $median; Min = $v[0]; Max = $v[$n - 1]; N = $n }
}

function Format-Number([double] $x, [bool] $count) {
  if ($count) { return $x.ToString('N0', $inv) }
  if ([Math]::Abs($x) -ge 100) { return $x.ToString('N0', $inv) }
  if ([Math]::Abs($x) -ge 10) { return $x.ToString('0.0', $inv) }
  return $x.ToString('0.00', $inv)
}

$csv = New-Object System.Collections.Generic.List[string]
$csv.Add('tool,vus,metric,median,min,max,runs')
$md = New-Object System.Collections.Generic.List[string]
$md.Add("Median (min${dash}max) over measured runs. Generated by ``benchmarks/summarize.ps1`` from ``runs.jsonl``.")
$md.Add('')

foreach ($metric in $metrics.Keys) {
  $md.Add("### $($metrics[$metric])")
  $md.Add('')
  $tools = @($rows | Select-Object -ExpandProperty tool -Unique)
  $md.Add('| VUs | ' + ($tools -join ' | ') + ' |')
  $md.Add('|---|' + (($tools | ForEach-Object { '---' }) -join '|') + '|')
  foreach ($vus in @($rows | Select-Object -ExpandProperty vus -Unique | Sort-Object)) {
    $cells = foreach ($tool in $tools) {
      $s = Get-Stats @($rows | Where-Object { $_.tool -eq $tool -and $_.vus -eq $vus } | ForEach-Object { $_.$metric })
      if ($null -eq $s) { 'not measured'; continue }
      $csv.Add([string]::Format($inv, '{0},{1},{2},{3},{4},{5},{6}', $tool, $vus, $metric, $s.Median, $s.Min, $s.Max, $s.N))
      $isCount = $metric -eq 'errors'
      '{0} ({1}{3}{2})' -f (Format-Number $s.Median $isCount), (Format-Number $s.Min $isCount), (Format-Number $s.Max $isCount), $dash
    }
    $md.Add("| $vus | " + ($cells -join ' | ') + ' |')
  }
  $md.Add('')
}

$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllLines((Join-Path $dir 'summary.csv'), $csv, $utf8)
[IO.File]::WriteAllLines((Join-Path $dir 'summary.md'), $md, $utf8)
Write-Host "wrote $(Join-Path $dir 'summary.csv') and summary.md"
